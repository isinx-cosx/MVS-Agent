// 下面这行的 `: number` 在运行时【完全不存在】。
// Node 做的事是：把 `: number` 删掉，然后把剩下的 JS 跑起来。
// C++ 的编译产物里有类型信息（vtable、模板实例、重载决议的结果）；JS 没有，一点都没有。
let 年龄: number = 30

console.log('=== 0. 类型只是注解 ===')
console.log('年龄 =', 年龄)

// 下面这行会在运行时打印 "number"。
// 但它是 JS 自己的 typeof，只认 6 个原始类型 + "object" + "function"，
// 它【不知道】你写的 `number` 注解。这两件事毫无关系。
console.log('typeof 年龄 =', typeof 年龄)

// ===========================================================================
// 1. 陷阱一：const 只锁「绑定」，不锁「内容」
// ===========================================================================
//
// C++：
//     const auto v = std::vector{1, 2};
//     v.push_back(3);   // ✗ 编译错误
//
// JS：
//     const v = [1, 2];
//     v.push(3);        // ✓ 完全合法
//
// 为什么？因为 JS 的 const 管的是「这个变量名还能不能指向别的东西」，
// 不是「这个东西本身能不能变」。它更像 C++ 的 `T* const`，而不是 `const T`。

console.log('\n=== 1. const 只锁绑定 ===')

const 列表 = [1, 2]
列表.push(3) // 合法！
console.log('列表 =', 列表)

// 只有「重新赋值」才会被拦下（下面这行如果取消注释会直接报错）：
// 列表 = [9]   // ✗ TypeError: Assignment to constant variable.

// 想要 C++ 那种「不可变」，JS 里必须用 Object.freeze（而且它只管一层，是浅的）：
const 冻结的 = Object.freeze([1, 2])
// 冻结的.push(3)   // ✗ TypeError: Cannot add property 2, object is not extensible

// ===========================================================================
// 2. 陷阱二：空值有两个，不是一个
// ===========================================================================
//
// C++：只有一个 nullptr。
// JS：undefined 和 null，而且是两回事。
//
//   undefined = "还没有值"      —— 系统给的。变量声明了没赋值、对象上不存在的属性、
//                                  函数没写 return，全是 undefined。
//   null      = "我明确要一个空" —— 你自己写的。
//
// 这个区别不是洁癖：TS 里 `x?: number` 得到的是 `number | undefined`，
// 而 `x: number | null` 是另一回事。仓库里到处是这两种写法，混了就看不出来。

console.log('\n=== 2. 两个空值 ===')

let 没赋值
console.log('没赋值 =', 没赋值, '| typeof =', typeof 没赋值)

const 明确的空 = null
console.log('明确的空 =', 明确的空, '| typeof =', typeof 明确的空) // 注意：是 "object"

const 对象 = { a: 1 }
console.log('不存在的属性 =', 对象['不存在的属性']) // undefined，不报错

// ⚠️ C++ 习惯会害你：C++ 里读一个不存在的成员是编译错误；
// JS 里读一个不存在的属性只得到 undefined，【静默】。这是 JS 最常见的 bug 来源。

// ===========================================================================
// 3. 陷阱三：默认是「引用」，而且没有拷贝构造
// ===========================================================================
//
// C++：
//     auto a = std::vector{1, 2};
//     auto b = a;          // 拷贝！a 和 b 是两个独立对象
//
// JS：除了几种「原始类型」，其余全是引用。赋值【不复制】。
// 而且 JS 里没有拷贝构造函数这种东西 —— 没有任何机制会在赋值时被自动调用。
//
// 这就是为什么 C++ 讲 RAII，JS 讲 try/finally：JS 里对象销毁由垃圾回收负责，
// 但「释放外部资源」这件事没人替你自动做。

console.log('\n=== 3. 默认是引用 ===')

const 甲 = { 名字: 'A' }
const 乙 = 甲 // 这不是拷贝！乙 和 甲 指向同一个对象
乙.名字 = 'B'
console.log('甲.名字 =', 甲.名字) // 'B' —— 改乙等于改甲

// 想真的复制，必须显式写：
const 丙 = { ...甲 } // 展开运算符，浅拷贝
丙.名字 = 'C'
console.log('甲.名字 =', 甲.名字) // 还是 'B'，丙 是独立的了
console.log('丙.名字 =', 丙.名字)

// 数组同理：
const 原始 = [1, 2, 3]
const 别名 = 原始
const 副本 = [...原始]
别名.push(4)
console.log('原始 =', 原始) // [1,2,3,4] —— 被别名改了
console.log('副本 =', 副本) // [1,2,3]   —— 不受影响

// ⚠️ 注意：`{...甲}` 是【浅】拷贝。如果属性本身是对象，那一层还是共享的。
// 深拷贝要显式用 structuredClone(甲)，仓库里没用过，暂时知道有这回事就行。

